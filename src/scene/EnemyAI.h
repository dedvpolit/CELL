// ============================================================================
// EnemyAI — состояния и восприятие: расстояние + прямая видимость
// (переиспользует LightBaking::HasLineOfSight — тот же трассировщик, что
// и у теней от факелов) + переключение Idle/Walk/Run + движение по пути
// с обходом стен (см. GridPathfinding.h — простой BFS по сетке карты,
// пересчитывается периодически, не каждый кадр).
//
// ПАТРУЛЬ (в Idle) — если враг никого не преследует, он не просто стоит:
// периодически выбирает случайную проходимую клетку карты и идёт туда
// пешком (обходя стены тем же путём, что и погоня), у цели ненадолго
// замирает, потом выбирает новую точку. "Просто наугад ходит и ищет
// игрока", как и просили — не полноценный ИИ-патруль по маршруту, а
// действительно случайный обход.
//
// ПАМЯТЬ О ПОСЛЕДНЕЙ ПОЗИЦИИ — если игрок пропадает из виду (спрятался
// за стену) во время Walk/Run, враг НЕ бросает погоню мгновенно: ещё
// kLoseTrackGrace (2.5с) секунд продолжает идти к ПОСЛЕДНЕЙ ВИДЕННОЙ
// позиции игрока (не наугад — именно туда, где видел в последний раз).
// Если снова увидел за это время — таймер сбрасывается, погоня
// продолжается как ни в чём не бывало. Если истекло — не мгновенно в
// патруль, а сперва SEARCH (см. ниже).
//
// УГОЛ ОБЗОРА (FOV) — раньше "видел" на 360° вокруг себя (только
// дистанция + прямая видимость, без направления). Теперь зрение
// ограничено конусом kFOVHalfAngleDeg от текущего yaw — за спиной не
// видит, даже если ничего не загораживает. Вплотную (kPeripheralRadius)
// замечает игрока в любом случае — "натолкнулся"/периферийное зрение, а
// не полноценное распознавание по центру взгляда.
//
// СЛУХ — независимо от зрения/FOV: пока враг в Idle (не преследует),
// шум от движения игрока (см. playerIsMoving/playerIsRunning) слышен
// СКВОЗЬ стены в радиусе kHearingRadiusWalk/Run (звук не имеет линии
// видимости). Услышанное — не то же самое, что увиденное: враг не
// срывается в погоню, а идёт ПРОВЕРИТЬ источник шума (SEARCH, см. ниже)
// на обычной скорости ходьбы.
//
// SEARCH — новое переходное состояние на замену мгновенному "потерял
// след -> сразу патруль". Используется в двух случаях: (1) истекла
// kLoseTrackGrace после погони, (2) услышал шум в Idle. Идёт к
// m_lastKnownPlayerPos (месту звука/последней видимой позиции), у цели
// недолго "оглядывается" (пауза, как и в патруле) и, если игрока так и
// не нашёл (перекрывается обычным восприятием выше — увидел за это
// время, значит уже не в Search), возвращается к обычному патрулю.
// Анимация переиспользует Walk/Idle — отдельного клипа нет (тот же
// приём, что и у патруля).
//
// ГИПОТЕЗЫ ПОБЕГА (m_searchWaypoints) — Search больше не ограничивается
// одной точкой. При входе в Search строится небольшая ЦЕПОЧКА точек для
// проверки по порядку (см. appendGuessedFleeWaypoints() в .cpp):
//   1) m_lastKnownPlayerPos — где реально видели/слышали игрока (как и
//      раньше, всегда первая).
//   2) Если в момент потери у врага было известно направление движения
//      игрока (m_playerHeading — оно копится каждый кадр из живой
//      playerPos независимо от видимости, тот же источник, что уже
//      использует упреждение Dash) — враг "додумывает" продолжение
//      маршрута: идёт по прямой вдоль этого направления (по сетке
//      коридоров, не по диагонали) до ближайшей стены/тупика.
//   3) Если по пути до этой стены попался боковой поворот — враг
//      ЗАОДНО заглядывает и туда (на пару клеток вглубь), на случай,
//      если игрок свернул, а не побежал по прямой до конца коридора.
// Если игрок в момент потери стоял на месте (heading слишком мал/не
// определён) — гипотез не добавляется, поведение точно как раньше
// (одна точка + пауза). У каждой промежуточной точки — короткая
// "заглянул" пауза (короче финальной), у последней в цепочке — прежняя
// более долгая "оглядывается", после которой враг сдаётся и уходит в
// патруль (см. движение ниже).
//
// SCREAM — разовый триггер: при СВЕЖЕМ обнаружении (переход из Idle/Walk
// в "достаточно близко и видит") враг сперва застывает и проигрывает
// Scream (1.25с — реальная длина клипа), и только потом срывается в
// Run. Пока играет Scream — не двигается (та же схема, что уже у
// Attack_Lunge/Wall_slam). Уже находясь в погоне, повторно Scream не
// проигрывается — только при первом обнаружении.
//
// РЫВОК (Dash) — под-состояние Run: раз в секунду во время преследования
// шанс сорваться в рывок — ×1.5 скорости, направление ФИКСИРУЕТСЯ в
// момент срыва, дальше рывок НЕ обновляет цель и НЕ идёт по пути
// (GridPathfinding игнорируется полностью — в этом и есть риск). Два
// исхода:
//   - врезался в игрока (дистанция < радиуса поимки) -> Attack_Lunge;
//   - врезался в стену (следующая клетка по курсу — стена) -> Wall_slam,
//     после — назад в Walk_Nervous (не Run!), даёт игроку окно на побег.
//
// Раньше направление рывка было ЧИСТО m_playerHeading (куда игрок
// двигался последним кадром) — если игрок стоял на месте или резко
// свернул, рывок улетал в сторону, выглядело случайно/глупо. Теперь
// направление — смесь "куда игрок движется" (упреждение, m_playerHeading
// с оценкой его скорости) И "где игрок СЕЙЧАС" (реальный вектор до
// игрока в момент срыва) — рывок целится туда, где игрок, вероятно,
// окажется, а не туда, где он был мгновение назад. Плюс перед стартом
// проверяется, что впереди по выбранному курсу есть хотя бы немного
// свободного места (см. m_dashDirection в .cpp) — рывок В УПОР В СТЕНУ
// с первого же кадра больше не срабатывает просто по вероятности; это
// не отменяет риск Wall_slam (курс всё ещё не пересчитывается на лету),
// просто отсеивает заведомо нелепые попытки.
//
// Поимка (Attack_Lunge) сигналит наружу через justCaughtPlayer() — см.
// DungeonScene::render(), где это транслируется в
// PlayerController::applyCaughtDebuff() (дебафф скорости игрока).
//
// КОЛЛАЙДЕР — цилиндрический (см. resolveWallCollision() ниже):
// применяется каждый кадр, во ВСЕХ состояниях, поверх любого движения
// (или его отсутствия) — гарантирует, что итоговая позиция никогда не
// пересекается со стеной/колонной, вместо того чтобы полагаться на то,
// что путь/Dash сами по себе никогда не подведут вплотную к геометрии.
// ============================================================================
class EnemyAI {
public:
    // Радиус цилиндрического коллайдера врага (см. resolveWallCollision()
    // в .cpp) — ПУБЛИЧНАЯ константа, а не локальная внутри .cpp, потому
    // что PlayerController тоже знает этот радиус (чтобы игрок физически
    // не проходил сквозь модель врага, см. PlayerController::
    // processInput()/tryMove() — там враг обрабатывается тем же приёмом
    // circle-vs-square, что и пьедестал кнопки победы). Одна константа
    // на оба места — та же логика, что и у WallShapes::kChamferSize
    // (общая для рендера и коллизии): нельзя, чтобы радиус коллизии
    // врага и радиус, которым его же "видит" игрок, разъехались по двум
    // независимым магическим числам.
    //
    // БАГФИКС ("игрок не может протиснуться и выбраться, если зажат с
    // врагом в тупике") — было 0.35, уменьшено до 0.30. Небольшое
    // уменьшение специально (в отличие от радиуса игрока, см. его
    // комментарий в PlayerController.h, который взял на себя основную
    // часть сокращения) — этот радиус приближает реальный силуэт 3D-
    // модели врага; уменьшать его сильно означало бы вернуть баг
    // "модель протыкает стены/игрока сквозь свой же коллайдер", который
    // чинили отдельно (см. resolveWallCollision()). 0.05 — минимум,
    // необходимый вместе с новым радиусом игрока (0.10), чтобы протиснуться
    // мимо врага в 1-юнитовом коридоре стало вообще геометрически
    // возможно: 0.30+0.10=0.40 против ширины коридора 1.0 (запас ~0.10
    // от половины коридора на каждую сторону).
    static constexpr float kCollisionRadius = 0.30f; // было 0.35

    // Сохраняет ссылки (не копии — карта не меняется после генерации
    // уровня) на данные, нужные HasLineOfSight()/патрулю. Вызывать один
    // раз после генерации карты (см. DungeonScene::loadMapAndGeometry()).
    void init(
        int mapW, int mapH,
        const std::vector<int>* map,
        const std::vector<WallShapes::CornerCut>* cornerCuts,
        const std::vector<unsigned char>* diagonalChainMask,
        const std::vector<glm::vec2>* columnCentersXZ,
        float columnRadius);

    void setPosition(const glm::vec3& pos) { m_position = pos; }
    glm::vec3 position() const { return m_position; }

    // УЛУЧШЕНИЕ ("на мини-карте отображать врага, если ИГРОК его уже
    // видел" — не наоборот) — true, пока "память" о последнем честном
    // зрительном контакте СО СТОРОНЫ ИГРОКА (FOV-конус + прямая
    // видимость от камеры игрока, см. playerCanSeeThisEnemy в
    // update()/DungeonScene::isEnemyVisibleToPlayer()) не истекла. Это
    // НЕЗАВИСИМАЯ система от восприятия самого ИИ (canSee внутри
    // update() — то, чем враг видит игрока, отвечает за погоню/Scream) —
    // раньше по ошибке был завязан именно на неё, что означало
    // противоположное запрошенному условие.
    //
    // УЛУЧШЕНИЕ ("сброс флага через какое-то время без контакта") —
    // раньше держался навсегда после первого срабатывания; теперь
    // "память" истекает через kSpottedMemoryDuration секунд БЕЗ нового
    // контакта (см. .cpp — таймер сбрасывается в ноль при каждом
    // повторном честном обнаружении и копится, пока враг не виден).
    //
    // Держится на весь текущий игровой сеанс (пока не создан новый
    // EnemyAI — новая игра/новая карта), но НЕ сохраняется в файл
    // сохранения: состояние ИИ (позиция/state/этот флаг) сейчас вообще
    // не участвует в SaveSystem — после "Продолжить" враг стартует как
    // будто только что заспавнился, это уже так было до этой правки и
    // не менялось здесь специально (отдельная, более крупная задача,
    // если понадобится).
    bool hasBeenSpottedByPlayer() const { return m_hasBeenSpotted; }
    void setHasBeenSpottedByPlayer(bool spotted) { m_hasBeenSpotted = spotted; }

    // УЛУЧШЕНИЕ ("пусть символ врага на мини-карте постепенно тухнет, а
    // не сразу исчезает") — раньше рендер читал напрямую
    // hasBeenSpottedByPlayer() (жёсткий 0/1), маркер щёлкал разом. Эта
    // функция вместо булева флага отдаёт плавную величину 0..1: полная
    // яркость (1.0), пока до истечения "памяти" остаётся больше
    // kSpottedFadeDuration секунд, дальше линейно гаснет до 0 ровно к
    // моменту истечения kSpottedMemoryDuration — тот же самый момент,
    // когда hasBeenSpottedByPlayer() стала бы false, просто с плавным
    // переходом перед этим, а не щелчком в этот самый момент.
    float spottedMarkerAlpha() const
    {
        if (!m_hasBeenSpotted)
            return 0.0f;
        const float remaining = kSpottedMemoryDuration - m_timeSinceLastSpotted;
        if (remaining >= kSpottedFadeDuration)
            return 1.0f;
        if (remaining <= 0.0f)
            return 0.0f;
        return remaining / kSpottedFadeDuration;
    }

    // Для отладки/будущего debug-overlay — не влияет на логику.
    const char* debugStateName() const;

    // true РОВНО ОДИН раз, в тот кадр, когда враг только что поймал
    // игрока (переход в Attack) — вызывающий код (DungeonScene) должен
    // считать этот флаг и сразу применить дебафф, он не повторяется
    // сам по себе (single-shot pulse, сбрасывается сразу после чтения).
    bool consumeJustCaughtPlayer();

    // playerPos/playerIsRunning/playerIsMoving — то, что уже известно
    // каждый кадр в DungeonScene::render(). playerIsMoving используется
    // отдельно от playerIsRunning для слуха (см. большой комментарий
    // класса выше) — тихая ходьба тоже слышна, просто на меньшей
    // дистанции, чем бег.
    //
    // playerInvisible — dev-tools ("в dev-tools добавить, чтобы игрок
    // становился невидимым для врага", см. PlayerController::
    // invisibleToEnemy()/клавиша I). Форсирует canSee=false для честного
    // зрительного обнаружения (FOV+LOS+радиус), независимо от реальной
    // геометрии — враг физически не может увидеть игрока, пока это true.
    // По отдельному запросу ("чтобы на I враг ещё и не слышал игрока")
    // ТАКЖЕ глушит слух (см. большой комментарий в .cpp у блока
    // восприятия шума) — I означает полную неприметность, не только
    // зрительную.
    //
    // playerCanSeeThisEnemy — УЛУЧШЕНИЕ ("на мини-карте: если ИГРОК
    // увидел врага, а не наоборот") — считается СНАРУЖИ, в
    // DungeonScene::isEnemyVisibleToPlayer() (FOV+LOS от камеры игрока
    // до этого конкретного врага), и управляет ТОЛЬКО
    // hasBeenSpottedByPlayer()/spottedMarkerAlpha() (мини-карта). Никак
    // не связано с canSee самого ИИ внутри update() — та отвечает за
    // погоню/Scream/слух, эта — только за то, что игрок УЖЕ УЗНАЛ про
    // конкретного врага.
    //
    // Двигает переданный EnemyCharacter и выставляет ему нужное
    // анимационное состояние.
    void update(float deltaTime, const glm::vec3& playerPos, bool playerIsRunning, bool playerIsMoving, bool playerInvisible, bool playerCanSeeThisEnemy, EnemyCharacter& character);

private:
    enum class AIState { Idle, Walk, Run, Dash, Attack, WallSlam, Scream, Search };
    AIState m_state = AIState::Idle;
    bool m_justCaughtPlayer = false;

    // См. hasBeenSpottedByPlayer()/spottedMarkerAlpha() выше.
    bool m_hasBeenSpotted = false;
    float m_timeSinceLastSpotted = 0.0f; // копится, пока враг НЕ виден
    static constexpr float kSpottedMemoryDuration = 20.0f; // сколько "помнит" игрок, что видел врага, без нового контакта
    static constexpr float kSpottedFadeDuration = 3.0f;    // за сколько секунд ДО истечения памяти маркер плавно гаснет (см. spottedMarkerAlpha())

    glm::vec3 m_position{ 0.0f };
    float m_yawDegrees = 0.0f;

    // ---- Оценка направления движения игрока (для рывка) ----
    glm::vec3 m_lastPlayerPos{ 0.0f };
    bool m_lastPlayerPosInit = false;
    glm::vec3 m_playerHeading{ 1.0f, 0.0f, 0.0f };

    // БАГФИКС ("проверка 'игрок стоял на месте' в appendGuessedFleeWaypoints
    // никогда не срабатывала") — m_playerHeading выше ВСЕГДА нормализуется
    // до длины ровно 1.0 (см. её присвоение в update()), либо остаётся
    // дефолтным (1,0,0) — тоже длина 1. Проверка "glm::length(heading) <
    // порог" в appendGuessedFleeWaypoints() поэтому была мертва: длина
    // практически никогда не опускалась ниже порога, гипотезы строились
    // ВСЕГДА, даже если игрок давно стоит неподвижно (используя
    // сколь угодно старое направление последнего реального движения).
    //
    // Вместо длины направления — отдельно копим РЕАЛЬНУЮ скорость игрока
    // (расстояние/deltaTime за кадр) и время с последнего момента, когда
    // она была выше kMeaningfulSpeed (см. update()) — короткий запас
    // (kFleeGuessMovementMemory в .cpp), чтобы один "неподвижный" кадр
    // (дрожание позиции камеры и т.п.) не стирал только что реальное
    // движение, но настоящая долгая неподвижность честно определялась
    // как "стоял на месте", как и было изначально задумано.
    float m_timeSinceMeaningfulMovement = 0.0f;

    // ---- Память о последней видимой позиции игрока (см. большой
    // комментарий класса выше) ----
    glm::vec3 m_lastKnownPlayerPos{ 0.0f };
    float m_lostTrackTimer = 0.0f;

    // ---- Патруль (см. большой комментарий класса выше) ----
    glm::vec3 m_patrolTarget{ 0.0f };
    bool m_hasPatrolTarget = false;
    bool m_patrolPaused = false;
    float m_patrolPauseTimer = 0.0f;

    // ---- Search — проверка последней известной позиции/источника шума
    // (см. большой комментарий класса выше). Отдельные поля от патруля
    // выше — Search логически не патруль (есть конкретная цель — место
    // шума/пропажи, а не случайная точка), хотя механика паузы у цели
    // та же самая.
    bool m_searchPaused = false;
    float m_searchPauseTimer = 0.0f;

    // Цепочка точек для проверки по порядку (см. "ГИПОТЕЗЫ ПОБЕГА" выше
    // и appendGuessedFleeWaypoints() в .cpp) — [0] всегда
    // m_lastKnownPlayerPos на момент входа в Search, дальше — 0-2
    // додуманные точки продолжения маршрута/бокового поворота.
    std::vector<glm::vec3> m_searchWaypoints;
    size_t m_searchWaypointIndex = 0;

    // ---- Рывок (Dash) ----
    std::mt19937 m_rng{ std::random_device{}() };
    float m_dashRollTimer = 0.0f;
    glm::vec3 m_dashDirection{ 0.0f };
    float m_dashElapsed = 0.0f;

    // ---- Attack_Lunge / Wall_slam / Scream — таймеры равны РЕАЛЬНОЙ
    // длительности клипов (проверено загрузчиком на настоящем файле).
    float m_stateTimer = 0.0f;

    // БАГФИКС ("временами анимации плохо срабатывают"): без этого,
    // сразу после Attack_Lunge враг возвращался в Run и МГНОВЕННО же
    // проверял дистанцию до игрока — а игрок как раз оглушён дебаффом
    // (см. PlayerController::applyCaughtDebuff()) и почти не может
    // отойти, так что получался мгновенный повторный захват:
    // Attack -> Run (доля кадра) -> Attack -> ... — выглядело как рябь/
    // заедание анимации. Короткое окно после атаки, пока повторная
    // поимка не засчитывается (враг всё ещё преследует, просто не может
    // ударить снова сразу же).
    float m_attackCooldownTimer = 0.0f;

    float m_perceptionTimer = 0.0f;

    // ---- Путь (общий для патруля И погони — см. followPath()) ----
    std::vector<glm::vec2> m_path;
    size_t m_pathWaypointIndex = 0;
    float m_pathRecomputeTimer = 0.0f;

    // Двигает m_position вдоль m_path к target (пересчитывая путь
    // периодически, не каждый кадр). Возвращает true, когда цель
    // достигнута (путь пройден до конца) — общий код для патруля и
    // Walk/Run-погони, чтобы не дублировать логику дважды.
    bool followPath(const glm::vec3& target, float speed, float deltaTime);

    bool isWalkableCell(int x, int z) const;
    glm::vec3 pickRandomPatrolPoint();

    // ---- Гипотезы побега (см. большой комментарий класса — "ГИПОТЕЗЫ
    // ПОБЕГА") — додумывает, куда мог убежать игрок из lastSeenPos,
    // исходя из направления его движения в момент потери (headingAtLoss,
    // это m_playerHeading на тот момент). Дописывает 0-2 точки в конец
    // outWaypoints (сам lastSeenPos туда не добавляет — вызывающий код
    // кладёт его первым отдельно).
    //
    // headingWasFresh — БАГФИКС: раньше "стоял на месте" определялось по
    // длине headingAtLoss, а она всегда ~1.0 (нормализованный вектор) —
    // проверка была мертва, гипотезы строились всегда. Теперь вызывающий
    // код (update()) сам решает свежесть по РЕАЛЬНОЙ скорости игрока (см.
    // m_timeSinceMeaningfulMovement в .h) и передаёт готовый флаг сюда —
    // false здесь означает "игрок не двигался достаточно недавно",
    // гипотез не добавляется, честная точка "видел здесь" остаётся
    // единственной, как и задумывалось изначально.
    void appendGuessedFleeWaypoints(const glm::vec3& lastSeenPos, const glm::vec3& headingAtLoss, bool headingWasFresh, std::vector<glm::vec3>& outWaypoints) const;

    // БАГФИКС ("модель проваливается в стену / застревает в стене, пока
    // ходил-искал игрока или после того, как врезался") — цилиндрический
    // коллайдер: выталкивает позицию наружу, если она (с радиусом
    // kCollisionRadius, см. .h выше) пересекается со стеной или колонной.
    // Не БЛОКИРУЕТ движение целиком, как PlayerController::tryMove — это
    // просто гарантия "итоговая позиция физически не может оказаться
    // внутри геометрии", применяется КАЖДЫЙ кадр перед setPosition() во
    // ВСЕХ ветках update() (движение по пути, Dash, заморозка на
    // Attack/WallSlam/Scream) — застрять "с концами" больше нельзя,
    // позицию выталкивает уже на следующем кадре, откуда бы она ни
    // взялась (в т.ч. если что-то поставило враг вплотную к стене до
    // этого фикса — сейв/спавн и т.п.).
    //
    // УПРОЩЕНИЕ (осознанное): проверяется против ПОЛНОГО квадрата
    // клетки (map[]==1), БЕЗ учёта декоративных срезанных углов
    // (WallShapes::CornerCut) — то есть враг физически держится чуть
    // дальше от угла, чем визуально вырезанный клин формально позволил
    // бы. Для игрока (PlayerController) срез учтён точно — там это
    // влияет на ощущение управления вплотную к стенам; для врага разница
    // на глаз незаметна, а простой квадрат надёжнее и дешевле (не нужно
    // тащить cornerCuts/chamfer-логику ещё и сюда) — единственный
    // эффект: враг чуть аккуратнее огибает срезанные углы, что
    // выглядит даже органичнее резкого среза "по кромке".
    glm::vec3 resolveWallCollision(const glm::vec3& pos) const;

    int m_mapW = 0, m_mapH = 0;
    const std::vector<int>* m_map = nullptr;
    const std::vector<WallShapes::CornerCut>* m_cornerCuts = nullptr;
    const std::vector<unsigned char>* m_diagonalChainMask = nullptr;
    const std::vector<glm::vec2>* m_columnCentersXZ = nullptr;
    float m_columnRadius = 0.0f;

    // БАГФИКС ("ИИ застревает в столбах") — колонны (см. Columns.h)
    // делают клетку map[]=2 ("пол"), НЕ 1 ("стена") — сама колонна лежит
    // ПОВЕРХ пола как отдельная круглая коллизия (m_columnCentersXZ),
    // независимая от сетки вообще. Для восприятия/движения (LOS, коллайдер
    // в resolveWallCollision()) это правильно и достаточно. НО для
    // path-поиска (isWalkableCell()/FindPath()/SmoothPath() ниже) —
    // катастрофа: центр колонны, (x+0.5, z+0.5), — это РОВНО та же точка,
    // которую pickRandomPatrolPoint() кладёт как цель патруля, и которую
    // FindPath() свободно прокладывает путь ЧЕРЕЗ такую клетку, как через
    // обычный пол (сетка о колонне ничего не знает). Враг либо получал
    // патрульную цель ровно в центре колонны — физически недостижимую
    // (коллайдер держит минимум kCollisionRadius+columnRadius от центра)
    // — и вечно тыкался в её невидимую оболочку, никогда не "приходя";
    // либо путь просто проходил СКВОЗЬ клетку колонны как через
    // промежуточную точку — то же самое липкое подёргивание, просто
    // посреди пути, а не в конце.
    //
    // Фикс: отдельная, СОБСТВЕННАЯ копия карты только для путей/патруля —
    // строится один раз в init() (см. .cpp), клетки с колоннами в ней
    // помечены как стена (1), хотя в исходном m_map (и везде за пределами
    // path-поиска — рендер, LOS, resolveWallCollision()) они по-прежнему
    // пол. Path-поиск в итоге просто ОБХОДИТ такие клетки, как обходил бы
    // настоящую стену — то же самое, что уже даёт корректный результат
    // для настоящих стен.
    std::vector<int> m_pathfindingMap;

    // ---- Анти-залипание — см. большой комментарий в .cpp у followPath() ----
    // Общий "последний рубеж" на случай, если путь/коллайдер всё равно
    // не уберегли от геометрической ловушки (тесный зазор у столба и
    // т.п.): отслеживает реальное продвижение тела за последние
    // kStuckCheckInterval секунд, независимо от КОНКРЕТНОЙ причины
    // затора — не пытается угадать/перечислить все возможные геометрии.
    float m_stuckCheckTimer = 0.0f;
    glm::vec3 m_stuckCheckRefPos{ 0.0f };
    bool m_stuckCheckRefInit = false;

    // ---- Звук (см. audio/EnemyAudio.h) ----
    EnemyAudio m_audio;

    // ---- Стоны (см. EnemyAudio::playMoan()) — редкие, ПОКА враг сам
    // бродит/ищет игрока (Idle-патруль или Search), НЕ во время реальной
    // погони (Walk/Run/Dash после обнаружения — там уже играет Scream/
    // погоня, стон не нужен и не запрашивался). Интервал каждый раз
    // рандомизируется заново (см. m_nextMoanInterval в .cpp) — не
    // регулярный тик, "изредка" в прямом смысле.
    float m_moanTimer = 0.0f;
    float m_nextMoanInterval = 10.0f; // переопределяется случайным в init()/первом тике

    // ---- Шаги врага — та же схема, что у PlayerController::
    // m_footstepDistance (см. большой комментарий у footstep-блока в
    // EnemyAI.cpp::update()): кадансим по РЕАЛЬНО пройденному за кадр
    // расстоянию тела, а не по отдельному таймеру, привязанный к
    // анимации, реально показанной в этом кадре (Walk/Run — включая
    // патруль и Search, которые переиспользуют Walk_Nervous), а не к
    // внутреннему AIState (Search/Idle-патруль формально не Walk/Run).
    float m_footstepDistance = 0.0f;
    bool m_footstepWasMoving = false;
    bool m_footstepWasRunning = false;
};
