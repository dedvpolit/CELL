#pragma once
#include <glm/glm.hpp>
#include <vector>

// ============================================================================
// GridPathfinding — простой BFS по сетке карты (та же сетка 1 клетка = 1
// юнит, что и везде в движке). Не A* — для равномерной по стоимости сетки
// (каждый шаг стоит одинаково) BFS даёт кратчайший путь ровно так же, как
// A* с нулевой эвристикой, просто проще в реализации и без риска
// ошибиться в эвристике. Карта 128x128 — полный обход в худшем случае
// это 16384 клетки, доли миллисекунды, поэтому пересчитывать чаще одного
// раза в несколько кадров (см. EnemyAI.cpp — не каждый кадр) более чем
// достаточно.
// ============================================================================
namespace GridPathfinding {

// Возвращает путь КЛЕТКАМИ (координаты сетки, не мировые) от start до
// goal включительно, либо пустой vector, если пути нет вообще
// (например, goal физически недостижим). isWalkable(x,z) — то же
// понятие "стена/не стена", что и everywhere в движке (map[]==1 —
// стена, всё остальное — проходимо).
std::vector<glm::ivec2> FindPath(
    int mapW, int mapH,
    const std::vector<int>& map,
    glm::ivec2 start,
    glm::ivec2 goal);

// true, если между клетками a и b нет стены НА ПРЯМОЙ линии между ними
// (супер-покрывающий Брезенхэм по клеткам, не по мировым координатам —
// оба конца всегда центры клеток, см. использование в SmoothPath ниже).
// Диагональный шаг (x и z меняются одновременно) считается блокирующим,
// если ОБЕ "боковые" клетки-соседа по диагонали — стены: иначе это было
// бы протискивание в щель толщиной в точку, геометрически невозможное
// (та же логика, что обычно используют для anti-corner-cutting в
// диагональном движении по сетке).
bool HasGridLineOfSight(
    int mapW, int mapH,
    const std::vector<int>& map,
    glm::ivec2 a,
    glm::ivec2 b);

// БАГФИКС/УЛУЧШЕНИЕ ("враг ходит зигзагом по клеткам вместо диагонали
// на открытых пространствах") — FindPath() выше это простой 4-directional
// BFS: он даёт кратчайший путь ПО ЧИСЛУ КЛЕТОК, но таких путей обычно
// много с одинаковой манхэттенской длиной, и BFS детерминированно берёт
// "лестницу" из чередующихся ортогональных шагов вместо одной диагонали
// — оба варианта одной длины для BFS, он не видит разницы. Переделывать
// сам BFS на 8-directional со честными диагональными весами — это уже
// не BFS, а Дейкстра/A* (диагональ стоит sqrt(2), не 1); вместо этого —
// пост-обработка (string pulling): убираем промежуточные точки пути там,
// где от текущей "закреплённой" точки и так уже видно по прямой более
// дальнюю — оставляем только точки, где путь реально меняет направление
// из-за стены. "Лестница" на открытом пространстве схлопывается в одну
// диагональ; там, где обход стены действительно нужен — лишние точки
// остаются как есть.
//
// ИЗВЕСТНОЕ ОГРАНИЧЕНИЕ: работает только с плоским map[] (стена/не
// стена), НЕ учитывает колонны (m_columnCentersXZ в EnemyAI) — как и сам
// followPath() в EnemyAI.cpp, который тоже не проверяет колонны при
// движении между waypoint'ами. Если понадобится — колонны нужно
// добавить в HasGridLineOfSight() отдельной проверкой, симметрично тому,
// как это уже сделано для линии видимости в LightBaking.
std::vector<glm::ivec2> SmoothPath(
    int mapW, int mapH,
    const std::vector<int>& map,
    const std::vector<glm::ivec2>& cellPath);

} // namespace GridPathfinding
