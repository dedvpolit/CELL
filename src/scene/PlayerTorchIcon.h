#pragma once
#include <GL/glew.h>

// ============================================================================
// STATUS: NOT CURRENTLY USED by DungeonScene. Пробовали заменить 3D-модель
// факела на плоскую 2D HUD-иконку (эта), но она визуально выбивалась из
// ASCII-стиля игры (гладкая векторная форма среди точечного ASCII-паттерна
// остального кадра) — вернулись к 3D-модели (см. PlayerTorchViewmodel.h),
// на этот раз с ориентацией только по yaw (без pitch), что структурно
// убирает баги вырождения векторов, из-за которых модель раньше пропадала.
// Оставлено здесь на случай, если понадобится HUD-элемент для чего-то
// другого — код рабочий и самодостаточный.
// ============================================================================

// ============================================================================
// PlayerTorchIcon — факел в руке игрока как ПЛОСКАЯ 2D HUD-иконка (по
// аналогии с ASCII-миникартой на компасе, клавиша V), а не как 3D-объект
// в мире. Рисуется своим отдельным крошечным шейдером
// (assets/shaders/player_torch_icon.{vert,frag}), экранным квадом БЕЗ
// view/projection вообще — просто фиксированные NDC-координаты в углу
// экрана, после AsciiEffect::end() (см. Application.cpp, там же, где
// renderCompassOverlay()/renderDebugMap()).
//
// Почему так, а не 3D-модель (см. историю правок,
// PlayerTorchViewmodel.h — теперь не используется): 3D-вариант требовал
// вычислять "право"/"верх" из направления камеры каждый кадр, что уже
// дважды приводило к багам (вырождение векторов при взгляде вверх/вниз,
// провал в стены через z-buffer). Плоская экранная иконка не зависит ни
// от камеры, ни от глубины сцены вообще — she не может "исчезнуть" или
// "провалиться в стену" в принципе, потому что не является частью 3D-мира.
// ============================================================================
class PlayerTorchIcon {
public:
    void create();
    void destroy();

    // timeSeconds — тот же uTime, что уже идёт в scene.frag (glfwGetTime()),
    // для мерцания/покачивания пламени.
    void render(int viewportWidth, int viewportHeight, float timeSeconds);

private:
    GLuint m_program = 0;
    GLuint m_vao = 0;
    GLuint m_vbo = 0;

    GLint m_uniIconCenter = -1;
    GLint m_uniIconHalfSize = -1;
    GLint m_uniTime = -1;
    void cacheUniformLocations();
};
